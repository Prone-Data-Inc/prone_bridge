const POOL_OF = {
  CI: 'westFrancophone',
  SN: 'westFrancophone',
  ML: 'westFrancophone',
  GN: 'westFrancophone',
  CM: 'cameroon',
  NG: 'nigeria',
  GH: 'ghana',
  KE: 'kenya',
  ZA: 'southAfrica',
  MA: 'morocco',
}

const plain = (text) =>
  text
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z]+/g, '')

/* { name, email } for a buyer in a country. The counter keeps every email different. */
export function buyerIdentity(rng, countryCode, counter) {
  const pool = POOLS[POOL_OF[countryCode] ?? 'westFrancophone']
  const first = rng.pick(pool.first)
  const last = rng.pick(pool.last)
  return { name: `${first} ${last}`, email: `${plain(first)}.${plain(last)}${counter}@example.com` }
}
