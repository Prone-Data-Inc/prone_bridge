/* Builds the "Prone Bridge" name as SVG path data. Same recipe as the Prone Data family: Outfit Light (the closest open
   geometric sans to the official name), thickened by a 6 unit outline so its stems match the official name, at the same
   capital height (282 units). Writes shared/src/brand/wordmark.js. */
import { createRequire } from 'node:module'
import { writeFileSync } from 'node:fs'
import * as fontkit from 'fontkit'

const require = createRequire(import.meta.url)
const CAP = 282
const STROKE = 6
const TEXT = 'Prone Bridge'

export function buildWordmark() {
  const font = fontkit.openSync(require.resolve('@fontsource/outfit/files/outfit-latin-300-normal.woff'))
  const scale = CAP / font.capHeight
  const run = font.layout(TEXT)
  let pen = 0
  const d = run.glyphs
    .map((glyph, i) => {
      const part = glyph.path
        .scale(scale, -scale)
        .translate(pen + STROKE / 2, CAP + STROKE / 2)
        .toSVG()
      pen += run.positions[i].xAdvance * scale
      return part
    })
    .join('')

  return {
    width: +(pen + STROKE).toFixed(2),
    capTop: 0,
    baseline: CAP + STROKE / 2,
    bottom: +(CAP + STROKE / 2 - run.bbox.minY * scale + STROKE / 2).toFixed(2),
    stroke: STROKE,
    d,
  }
}

export function writeWordmark(file) {
  const wordmark = buildWordmark()
  const source = `/* Generated by \`npm run brand\` from Outfit Light. Do not edit by hand. */\nexport const WORDMARK = ${JSON.stringify(wordmark)}\n`
  writeFileSync(file, source)
  return wordmark
}
